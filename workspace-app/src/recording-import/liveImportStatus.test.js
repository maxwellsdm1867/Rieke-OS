import test from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer,{act} from 'react-test-renderer';
import {createServer} from '../test-support/isolatedVite.js';
import {fileURLToPath} from 'node:url';
test('active progress survives notification timeout and follows stage counters',async t=>{
 const server=await createServer({root:fileURLToPath(new URL('../..',import.meta.url)),configFile:false,server:{middlewareMode:true,hmr:false,ws:false},appType:'custom',logLevel:'error',esbuild:{jsx:'automatic'}});
 const {default:Status}=await server.ssrLoadModule('/src/recording-import/ui/ImportStatusBar.jsx');
 let renderer;
 t.after(async()=>{await act(()=>renderer?.unmount());t.mock.timers.reset();await server.close();});
 let job={job_uuid:'one',status:'validating',source:'recording.h5',progress:{stage_label:'Validating epochs',completed:1,total:10,unit:'epochs'}};
 let props={monitor:{data:{jobs:[job]},observedAt:Date.now()},onOpen(){}};
 const render=()=>act(()=>{if(renderer)renderer.update(React.createElement(Status,props));else renderer=TestRenderer.create(React.createElement(Status,props));});
 t.mock.timers.enable({apis:['setTimeout']});await render();
 await act(()=>t.mock.timers.tick(11000));
 assert.equal(renderer.root.findByType('aside').props['aria-label'],'Live import status');
 assert.equal(renderer.root.findByType('progress').props.value,1);
 job={...job,progress:{...job.progress,completed:7}};props={...props,monitor:{...props.monitor,data:{jobs:[job]}}};await render();
 assert.equal(renderer.root.findByType('progress').props.value,7);
 props={...props,monitor:{...props.monitor,connectionError:'offline'}};await render();
 assert.match(JSON.stringify(renderer.toJSON()),/last confirmed progress/);
 props={...props,monitor:{data:{jobs:[{...job,status:'complete'}]},observedAt:Date.now()}};await render();
 assert.equal(renderer.root.findByType('aside').props['aria-label'],'Import notification');
 await act(()=>t.mock.timers.tick(11000));assert.equal(renderer.toJSON(),null);
 props={...props,transfer:{phase:'awaiting_job',filename:'next.h5',started_at:'now'}};await render();
 await act(()=>t.mock.timers.tick(11000));assert.match(JSON.stringify(renderer.toJSON()),/Waiting for import acceptance/);
 assert.equal(renderer.root.findByType('progress').props.value,undefined);
 props={...props,transfer:{...props.transfer,phase:'accepted',job_uuid:'pending'},monitor:{data:{jobs:[null]},connectionError:'offline'}};await render();
 await act(()=>t.mock.timers.tick(11000));assert.match(JSON.stringify(renderer.toJSON()),/Import accepted/);
 assert.equal(renderer.root.findByType('progress').props.value,undefined);
});
